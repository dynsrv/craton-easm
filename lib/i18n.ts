export function tlsLabel(daysLeft: number | null, t: Dict): { text: string; tone: 'muted' | 'bad' | 'warn' | 'ok' } {
  if (daysLeft == null) return { text: t.noTls, tone: 'muted' };
  if (daysLeft < 0) return { text: t.expired(-daysLeft), tone: 'bad' };
  return { text: t.days(daysLeft), tone: daysLeft < 30 ? 'warn' : 'ok' };
}

